export function getProductImage(product) {
  if (product?.imageUrl && product.imageUrl.trim() !== '') {
    return product.imageUrl;
  }
  const name = (product?.name || '').toLowerCase();
  for (const [key, url] of Object.entries(ITEM_IMAGES)) {
    if (name.includes(key)) return url;
  }
  const catName = typeof product?.categoryId === 'object' ? product?.categoryId?.name : product?.categoryName;
  if (catName && CATEGORY_DEFAULT_IMAGES[catName]) {
    return CATEGORY_DEFAULT_IMAGES[catName];
  }
  return 'https://images.unsplash.com/photo-1542838132-92c53300491e?w=400&auto=format&fit=crop&q=80';
}
